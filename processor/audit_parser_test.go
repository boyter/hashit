func TestSplitHashdeepLine(t *testing.T) {
	cases := []struct {
		line        string
		columns     int
		filenameIdx int
		want        []string
	}{
		{"2,abc,def,a.txt", 4, 3, []string{"2", "abc", "def", "a.txt"}},
		{"2,abc,def,b, with comma.txt", 4, 3, []string{"2", "abc", "def", "b, with comma.txt"}},
		{`2,abc,def,c "quoted".txt`, 4, 3, []string{"2", "abc", "def", `c "quoted".txt`}},
		{"2,abc,def, spaced .txt ", 4, 3, []string{"2", "abc", "def", " spaced .txt "}},
		{"2,abc,a,b.txt,2026-01-01 10:00:00", 4, 2, []string{"2", "abc", "a,b.txt", "2026-01-01 10:00:00"}},
	}

	for _, c := range cases {
		got, err := splitHashdeepLine(c.line, c.columns, c.filenameIdx)
		if err != nil {
			t.Fatalf("%q: unexpected error %v", c.line, err)
		}
		for i := range c.want {
			if got[i] != c.want[i] {
				t.Errorf("%q: column %d expected %q got %q", c.line, i, c.want[i], got[i])
			}
		}
	}

	if _, err := splitHashdeepLine("2,abc", 4, 3); err == nil {
		t.Error("expected error for line with too few columns")
	}
}

func TestNewAuditorHashdeepMd5Only(t *testing.T) {
	// hashit 1.4.0 with -c md5 wrote only the md5 column, which previously caused every file to
	// be reported as modified as the empty sha256 never matched
	input := "%%%% HASHDEEP-1.0\n%%%% size,md5,filename\n## Invoked from: /srv/media\n##\n2," + testMD5 + ",a.txt\n"
	hdl, err := NewAuditor(input, "/srv/media/hashes.txt")
	if err != nil {
		t.Fatal(err)
	}

	if len(hdl.HashNames()) != 1 || hdl.HashNames()[0] != "md5" {
		t.Errorf("expected only md5 to be required got %v", hdl.HashNames())
	}

	_, status := hdl.Find(Result{File: "a.txt", MD5: testMD5, SHA256: testSHA256, Bytes: 2})
	if status != FileMatched {
		t.Errorf("expected match got %v", status)
	}
}

func TestNewAuditorHashdeepInvokedFrom(t *testing.T) {
	input := "%%%% HASHDEEP-1.0\n%%%% size,md5,sha256,filename\n## Invoked from: /srv/media\n##\n2," + testMD5 + "," + testSHA256 + ",./sub/a.txt\n"
	hdl, err := NewAuditor(input, "hashes.txt")
	if err != nil {
		t.Fatal(err)
	}

	// relative paths in the file are relative to where hashdeep was invoked from, so an absolute
	// path on disk should match, as should the same relative path without the ./ prefix
	for _, f := range []string{"/srv/media/sub/a.txt", "sub/a.txt", "./sub/a.txt"} {
		if hdl.Lookup(f) == nil {
			t.Errorf("expected %s to be found", f)
		}
	}
}

func TestNewAuditorHashdeepMultipleHeaders(t *testing.T) {
	input := "%%%% HASHDEEP-1.0\n%%%% size,md5,filename\n2," + testMD5 + ",a.txt\n" +
		"%%%% HASHDEEP-1.0\n%%%% size,sha1,sha256,tiger,filename\n2," + testSHA1 + "," + testSHA256 + ",deadbeef,b.txt\n"
	hdl, err := NewAuditor(input, "hashes.txt")
	if err != nil {
		t.Fatal(err)
	}

	if hdl.Count() != 2 {
		t.Fatalf("expected 2 records got %d", hdl.Count())
	}

	r := hdl.Lookup("b.txt")
	if r == nil || r.Hashes["sha1"] != testSHA1 || r.Hashes["sha256"] != testSHA256 {
		t.Errorf("expected sha1 and sha256 for b.txt got %v", r)
	}
	if r.Hashes["tiger"] != "deadbeef" {
		t.Errorf("expected tiger for b.txt got %v", r.Hashes)
	}
}

