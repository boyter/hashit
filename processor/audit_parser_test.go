func TestAuditorFindMoved(t *testing.T) {
	input := "%%%% HASHDEEP-1.0\n%%%% size,md5,sha256,filename\n" +
		"2," + testMD5 + "," + testSHA256 + ",a.txt\n" +
		"2," + testMD5 + "," + testSHA256 + ",copy.txt\n"
	hdl, err := NewAuditor(input, "hashes.txt")
	if err != nil {
		t.Fatal(err)
	}

	// two identical files moved should each find a distinct record
	first := hdl.FindMoved(Result{File: "x.txt", MD5: testMD5, SHA256: testSHA256, Bytes: 2})
	second := hdl.FindMoved(Result{File: "y.txt", MD5: testMD5, SHA256: testSHA256, Bytes: 2})
	third := hdl.FindMoved(Result{File: "z.txt", MD5: testMD5, SHA256: testSHA256, Bytes: 2})
	if first == nil || second == nil || first == second {
		t.Errorf("expected two distinct moved records got %v %v", first, second)
	}
	if third != nil {
		t.Error("expected no record left for a third copy")
	}

	// size must match as well as hashes
	hdl, _ = NewAuditor(input, "hashes.txt")
	if hdl.FindMoved(Result{File: "x.txt", MD5: testMD5, SHA256: testSHA256, Bytes: 3}) != nil {
		t.Error("expected size mismatch to not be a move")
	}
}

func TestAuditorExclude(t *testing.T) {
	dir := t.TempDir()
	input := "%%%% HASHDEEP-1.0\n%%%% size,md5,filename\n## Invoked from: " + dir + "\n" +
		"2," + testMD5 + ",a.txt\n" +
		"1120," + testMD5 + ",hashes.txt\n"
	hdl, err := NewAuditor(input, filepath.Join(dir, "hashes.txt"))
	if err != nil {
		t.Fatal(err)
	}

	hdl.Exclude(filepath.Join(dir, "hashes.txt"))
	if hdl.Count() != 1 || hdl.Lookup(filepath.Join(dir, "hashes.txt")) != nil {
		t.Errorf("expected audit file to be excluded got %d records", hdl.Count())
	}
}

