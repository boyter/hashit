func TestNewAuditorSumFormats(t *testing.T) {
	cases := map[string]string{
		"gnu text":   testMD5 + "  a.txt\n",
		"gnu binary": testMD5 + " *a.txt\n",
		"uppercase":  "60B725F10C9C85C70D97880DFE8191B3  a.txt\n",
		"bsd tag":    "MD5 (a.txt) = " + testMD5 + "\n",
		"comments":   "# generated by something\n; another comment\n\n" + testMD5 + "  a.txt\n",
		"mtime":      testMD5 + "  a.txt\n2026-01-01 10:00:00  a.txt\n",
	}

	for name, input := range cases {
		hdl, err := NewAuditor(input, "hashes.md5")
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if hdl.Count() != 1 {
			t.Errorf("%s: expected 1 record got %d", name, hdl.Count())
		}
		if _, status := hdl.Find(Result{File: "a.txt", MD5: testMD5, Bytes: 2}); status != FileMatched {
			t.Errorf("%s: expected match got %v", name, status)
		}
	}
}

func TestNewAuditorSumMultipleHashes(t *testing.T) {
	// hashit's sum format writes one line per hash
	input := testMD5 + "  a.txt\n" + testSHA1 + "  a.txt\n" + testSHA256 + "  a.txt\n"
	hdl, err := NewAuditor(input, "hashes.sum")
	if err != nil {
		t.Fatal(err)
	}

	if hdl.Count() != 1 || len(hdl.HashNames()) != 3 {
		t.Fatalf("expected 1 record with 3 hashes got %d records and %v", hdl.Count(), hdl.HashNames())
	}

	if _, status := hdl.Find(Result{File: "a.txt", MD5: testMD5, SHA1: testSHA1, SHA256: "00", Bytes: 2}); status != FileModified {
		t.Errorf("expected modified when any hash differs got %v", status)
	}
}

